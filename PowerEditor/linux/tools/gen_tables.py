"""Generate the C++ tables used by the Linux (Qt) front end directly from the
Windows sources, so menus, default shortcuts and the language list stay in
sync with the Win32 build.

Usage: gen_tables.py <PowerEditor/src> <PowerEditor/installer> <out dir>

Reads
  Notepad_plus.rc                              main menu (IDR_M30_MENU)
  Parameters.cpp                               default shortcuts (winKeyDefs)
  localization.cpp                             menu ids used by nativeLang files
  Notepad_plus.cpp                             menuID2LangType()
  ScintillaComponent/ScintillaEditView.cpp     language <-> lexer table
  MISC/PluginsManager/Notepad_plus_msgs.h      enum LangType
  installer/nativeLang/english.xml             sub menu ids (fallback match)
Writes
  LangType.h, LangTable.inc, MenuTable.inc, ShortcutTable.inc
"""

import os
import re
import sys
import xml.etree.ElementTree as ET


def read(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        return f.read()


def write_if_changed(path, text):
    old = None
    if os.path.exists(path):
        old = read(path)
    if old != text:
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)


def cstr(s):
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\n":
            out.append("\\n")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def unrc(s):
    # resource-script string escapes
    s = s.replace('""', '"')
    return s.replace("\\t", "\t").replace("\\\\", "\\")


def norm_label(s):
    return re.sub(r"[^a-z0-9+]", "", s.replace("&", "").lower())


HEADER = "// Generated by PowerEditor/linux/tools/gen_tables.py -- do not edit.\n"


# --------------------------------------------------------------------------
# enum LangType
# --------------------------------------------------------------------------
def gen_langtype(src):
    text = read(os.path.join(src, "MISC", "PluginsManager", "Notepad_plus_msgs.h"))
    m = re.search(r"enum\s+LangType\s*\{(.*?)\};", text, re.S)
    if not m:
        sys.exit("gen_tables: enum LangType not found")
    body = re.sub(r"//[^\n]*", "", m.group(1)).replace("\\", " ")
    names = [n.strip() for n in body.split(",") if n.strip()]
    lines = [HEADER, "#pragma once\n\n", "enum LangType\n{\n"]
    lines += ["\t%s,\n" % n for n in names]
    lines.append("};\n")
    return "".join(lines), names


# --------------------------------------------------------------------------
# language table + menu id -> language
# --------------------------------------------------------------------------
def gen_langtable(src):
    sev = read(os.path.join(src, "ScintillaComponent", "ScintillaEditView.cpp"))
    rows = re.findall(r'\{L"([^"]*)",\s*L"([^"]*)",\s*L"([^"]*)",\s*(L_\w+),\s*"([^"]*)"\}', sev)
    if not rows:
        sys.exit("gen_tables: _langNameInfoArray not found")

    npp = read(os.path.join(src, "Notepad_plus.cpp"))
    m = re.search(r"LangType\s+Notepad_plus::menuID2LangType\s*\(int cmdID\)\s*\{(.*?)\n\}", npp, re.S)
    if not m:
        sys.exit("gen_tables: menuID2LangType not found")
    pairs = []
    pending = []
    for tok in re.finditer(r"case\s+(IDM_LANG_\w+)\s*:|return\s+(L_\w+)\s*;", m.group(1)):
        if tok.group(1):
            pending.append(tok.group(1))
        else:
            for c in pending:
                pairs.append((c, tok.group(2)))
            pending = []

    out = [HEADER, "\n"]
    out.append("static const LanguageNameInfo kLangNameInfo[] = {\n")
    for name, short, long_, lt, lexer in rows:
        out.append("\t{%s, %s, %s, %s, %s},\n" % (cstr(name), cstr(short), cstr(long_), lt, cstr(lexer)))
    out.append("};\n\n")
    out.append("static const struct { int menuId; LangType lang; } kMenuIdToLang[] = {\n")
    for c, lt in pairs:
        out.append("\t{%s, %s},\n" % (c, lt))
    out.append("};\n")
    return "".join(out)


# --------------------------------------------------------------------------
# main menu
# --------------------------------------------------------------------------
def parse_rc_menu(src):
    rc = read(os.path.join(src, "Notepad_plus.rc"))
    start = rc.find("IDR_M30_MENU MENU")
    if start < 0:
        sys.exit("gen_tables: IDR_M30_MENU not found")
    root = {"kind": "popup", "label": "", "children": []}
    stack = [root]
    depth = 0
    last_popup = None
    for raw in rc[start:].splitlines()[1:]:
        line = raw.strip()
        if not line or line.startswith("//"):
            continue
        if line == "BEGIN":
            depth += 1
            if depth > 1:
                stack.append(last_popup)
            continue
        if line == "END":
            depth -= 1
            if depth == 0:
                break
            stack.pop()
            continue
        m = re.match(r'POPUP\s+"((?:[^"]|"")*)"', line)
        if m:
            last_popup = {"kind": "popup", "label": unrc(m.group(1)), "children": []}
            stack[-1]["children"].append(last_popup)
            continue
        if re.match(r"MENUITEM\s+SEPARATOR", line):
            stack[-1]["children"].append({"kind": "sep"})
            continue
        m = re.match(r'MENUITEM\s+"((?:[^"]|"")*)"\s*,\s*(\w+)\s*(.*)', line)
        if m:
            stack[-1]["children"].append({"kind": "item", "label": unrc(m.group(1)),
                                          "id": m.group(2), "grayed": "GRAYED" in m.group(3)})
            continue
        sys.exit("gen_tables: cannot parse menu line: " + raw)
    return root


def gen_menutable(src, installer):
    root = parse_rc_menu(src)

    # Same choices Notepad++ makes at run time: keep the compact (grouped)
    # Language menu, drop the tab-bar helper entries of the menu bar.
    top = []
    seen_language = False
    for child in root["children"]:
        if child["kind"] != "popup":
            continue
        if child["label"] == "▼":
            continue
        if child["label"] == "&Language" and not seen_language:
            seen_language = True
            continue
        top.append(child)

    # positional ids from localization.cpp
    loc = read(os.path.join(src, "localization.cpp"))
    pos2id = {}
    for a, b, c, key in re.findall(r'\{\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*(-?\d+)\s*,\s*"([^"]+)"\s*\}', loc):
        pos2id[(int(a), int(b), int(c))] = key

    # english names of sub menu ids (to validate / fall back)
    eng_sub = {}
    eng_main = {}
    try:
        tree = ET.parse(os.path.join(installer, "nativeLang", "english.xml"))
        for it in tree.getroot().iter("Item"):
            if "subMenuId" in it.attrib:
                eng_sub[it.attrib["subMenuId"]] = it.attrib.get("name", "")
            elif "menuId" in it.attrib:
                eng_main[it.attrib["menuId"]] = it.attrib.get("name", "")
    except (OSError, ET.ParseError):
        pass
    label2sub = {norm_label(v): k for k, v in eng_sub.items()}

    out = [HEADER, "\n", "static const MenuTableEntry kMenuTable[] = {\n"]

    def key_for(path, label):
        if len(path) == 1:
            return pos2id.get((path[0], -1, -1), "")
        p = tuple(path) + (-1,) * (3 - len(path))
        key = pos2id.get(p, "")
        if key and norm_label(eng_sub.get(key, label)) == norm_label(label):
            return key
        return label2sub.get(norm_label(label), key)

    def emit(node, path, indent):
        for idx, child in enumerate(node["children"]):
            pad = "\t" * indent
            if child["kind"] == "sep":
                out.append("%s{MenuEntryKind::Separator, \"\", 0, \"\", false},\n" % pad)
            elif child["kind"] == "item":
                out.append("%s{MenuEntryKind::Item, %s, %s, \"\", %s},\n"
                           % (pad, cstr(child["label"]), child["id"], "true" if child["grayed"] else "false"))
            else:
                p = path + [idx]
                out.append("%s{MenuEntryKind::PopupBegin, %s, 0, %s, false},\n"
                           % (pad, cstr(child["label"]), cstr(key_for(p, child["label"]))))
                emit(child, p, indent + 1)
                out.append("%s{MenuEntryKind::PopupEnd, \"\", 0, \"\", false},\n" % pad)

    for i, menu in enumerate(top):
        out.append("\t{MenuEntryKind::PopupBegin, %s, 0, %s, false},\n"
                   % (cstr(menu["label"]), cstr(key_for([i], menu["label"]))))
        emit(menu, [i], 2)
        out.append("\t{MenuEntryKind::PopupEnd, \"\", 0, \"\", false},\n")
    out.append("};\n")
    return "".join(out)


