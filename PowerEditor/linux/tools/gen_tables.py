VK_SPECIAL = {
    "VK_BACK": "Key_Backspace", "VK_TAB": "Key_Tab", "VK_RETURN": "Key_Return",
    "VK_ESCAPE": "Key_Escape", "VK_SPACE": "Key_Space", "VK_PRIOR": "Key_PageUp",
    "VK_NEXT": "Key_PageDown", "VK_END": "Key_End", "VK_HOME": "Key_Home",
    "VK_LEFT": "Key_Left", "VK_UP": "Key_Up", "VK_RIGHT": "Key_Right",
    "VK_DOWN": "Key_Down", "VK_INSERT": "Key_Insert", "VK_DELETE": "Key_Delete",
    "VK_MULTIPLY": "Key_Asterisk", "VK_ADD": "Key_Plus", "VK_SUBTRACT": "Key_Minus",
    "VK_DECIMAL": "Key_Period", "VK_DIVIDE": "Key_Slash",
    "VK_OEM_1": "Key_Semicolon", "VK_OEM_PLUS": "Key_Equal", "VK_OEM_COMMA": "Key_Comma",
    "VK_OEM_MINUS": "Key_Minus", "VK_OEM_PERIOD": "Key_Period", "VK_OEM_2": "Key_Slash",
    "VK_OEM_3": "Key_QuoteLeft", "VK_OEM_4": "Key_BracketLeft", "VK_OEM_5": "Key_Backslash",
    "VK_OEM_6": "Key_BracketRight", "VK_OEM_7": "Key_Apostrophe",
}


def vk_to_qt(vk):
    if vk in VK_SPECIAL:
        return VK_SPECIAL[vk]
    m = re.fullmatch(r"VK_([A-Z0-9])", vk)
    if m:
        return "Key_" + m.group(1)
    m = re.fullmatch(r"VK_F(\d+)", vk)
    if m:
        return "Key_F" + m.group(1)
    m = re.fullmatch(r"VK_NUMPAD(\d)", vk)
    if m:
        return "Key_" + m.group(1)
    return None


# Shortcuts of Parameters.cpp bound to internal commands (resource.h) instead of menu commands
SHORTCUT_ID_MAP = {
    "IDC_PREV_DOC": ["IDM_VIEW_TAB_PREV"],
    "IDC_NEXT_DOC": ["IDM_VIEW_TAB_NEXT"],
    # start and stop are never enabled together, so one key toggles recording
    "IDC_EDIT_TOGGLEMACRORECORDING": ["IDM_MACRO_STARTRECORDINGMACRO", "IDM_MACRO_STOPRECORDINGMACRO"],
}


def gen_shortcuts(src):
    menu_ids = set(re.findall(r"define\s+(IDM_\w+)", read(os.path.join(src, "menuCmdID.h"))))
    params = read(os.path.join(src, "Parameters.cpp"))
    m = re.search(r"winKeyDefs\[\]\s*\{(.*?)\n\};", params, re.S)
    if not m:
        sys.exit("gen_tables: winKeyDefs not found")
    out = [HEADER, "\n", "static const ShortcutTableEntry kShortcutTable[] = {\n"]
    for vk, cmd, ctrl, alt, shift in re.findall(
            r"\{\s*(VK_\w+)\s*,\s*(\w+)\s*,\s*(true|false)\s*,\s*(true|false)\s*,\s*(true|false)\s*,", m.group(1)):
        if vk == "VK_NULL":
            continue
        key = vk_to_qt(vk)
        if not key:
            sys.stderr.write("gen_tables: unmapped key %s for %s\n" % (vk, cmd))
            continue
        mods = []
        if ctrl == "true":
            mods.append("Qt::ControlModifier")
        if alt == "true":
            mods.append("Qt::AltModifier")
        if shift == "true":
            mods.append("Qt::ShiftModifier")
        if vk.startswith("VK_NUMPAD") or vk in ("VK_ADD", "VK_SUBTRACT", "VK_DIVIDE", "VK_MULTIPLY", "VK_DECIMAL"):
            mods.append("Qt::KeypadModifier")
        modexpr = " | ".join(mods) if mods else "Qt::NoModifier"
        for target in SHORTCUT_ID_MAP.get(cmd, [cmd]):
            if target not in menu_ids:
                sys.stderr.write("gen_tables: %s is not a menu command, shortcut skipped\n" % target)
                continue
            out.append("\t{%s, Qt::KeyboardModifiers(%s), Qt::%s},\n" % (target, modexpr, key))
    out.append("};\n")
    return "".join(out)


VK_CODES = {
    "VK_BACK": 0x08, "VK_TAB": 0x09, "VK_RETURN": 0x0D, "VK_ESCAPE": 0x1B, "VK_SPACE": 0x20,
    "VK_PRIOR": 0x21, "VK_NEXT": 0x22, "VK_END": 0x23, "VK_HOME": 0x24, "VK_LEFT": 0x25,
    "VK_UP": 0x26, "VK_RIGHT": 0x27, "VK_DOWN": 0x28, "VK_INSERT": 0x2D, "VK_DELETE": 0x2E,
    "VK_MULTIPLY": 0x6A, "VK_ADD": 0x6B, "VK_SUBTRACT": 0x6D, "VK_DECIMAL": 0x6E, "VK_DIVIDE": 0x6F,
    "VK_OEM_1": 0xBA, "VK_OEM_PLUS": 0xBB, "VK_OEM_COMMA": 0xBC, "VK_OEM_MINUS": 0xBD,
    "VK_OEM_PERIOD": 0xBE, "VK_OEM_2": 0xBF, "VK_OEM_3": 0xC0, "VK_OEM_4": 0xDB, "VK_OEM_5": 0xDC,
    "VK_OEM_6": 0xDD, "VK_OEM_7": 0xDE, "VK_OEM_102": 0xE2, "VK_NULL": 0,
}


def vk_code(vk):
    vk = vk.strip()
    if vk == "0":
        return 0
    if vk in VK_CODES:
        return VK_CODES[vk]
    m = re.fullmatch(r"VK_([A-Z0-9])", vk)
    if m:
        return ord(m.group(1))
    m = re.fullmatch(r"VK_F(\d+)", vk)
    if m:
        return 0x6F + int(m.group(1))
    m = re.fullmatch(r"VK_NUMPAD(\d)", vk)
    if m:
        return 0x60 + int(m.group(1))
    return None


def gen_scintillakeys(src):
    # scintKeyDefs of Parameters.cpp: the Scintilla commands of the Shortcut Mapper
    text = read(os.path.join(src, "Parameters.cpp"))
    m = re.search(r"scintKeyDefs\[\]\s*\{(.*?)\n\};", text, re.S)
    if not m:
        sys.exit("gen_tables: scintKeyDefs not found in Parameters.cpp")
    out = [HEADER, "static const ScintillaKeyTableEntry kScintillaKeyTable[] = {"]
    for line in m.group(1).splitlines():
        line = line.strip()
        if line.startswith("//"):
            continue
        e = re.match(r'\{L"([^"]*)",\s*(\w+),\s*(true|false),\s*(true|false),\s*(true|false),\s*(\w+),\s*(\w+)\}', line)
        if not e:
            continue
        name, sci, ctrl, alt, shift, vk, menu = e.groups()
        code = vk_code(vk)
        if code is None:
            sys.stderr.write("gen_tables: unmapped key %s for %s\n" % (vk, sci))
            continue
        out.append('\t{"%s", %s, %s, %s, %s, %d, %s},' % (name, sci, ctrl, alt, shift, code, menu))
    out.append("};")
    return "\n".join(out) + "\n"


def gen_contextmenu(src):
    # CONTEXTMENU_XML_CONTENT of NppConstants.h: the default contextMenu.xml (the header needs windows.h)
    text = read(os.path.join(src, "MISC", "Common", "NppConstants.h"))
    m = re.search(r'CONTEXTMENU_XML_CONTENT\[\]\s*=\s*(".*?[^\\]");\s*\n', text, re.S)
    if not m:
        sys.exit("gen_tables: CONTEXTMENU_XML_CONTENT not found in NppConstants.h")
    return HEADER + "static const char kContextMenuXmlDefault[] = " + m.group(1) + ";\n"


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    src, installer, outdir = sys.argv[1:4]
    os.makedirs(outdir, exist_ok=True)
    langtype, _ = gen_langtype(src)
    write_if_changed(os.path.join(outdir, "LangType.h"), langtype)
    write_if_changed(os.path.join(outdir, "LangTable.inc"), gen_langtable(src))
    write_if_changed(os.path.join(outdir, "MenuTable.inc"), gen_menutable(src, installer))
    write_if_changed(os.path.join(outdir, "ShortcutTable.inc"), gen_shortcuts(src))
    write_if_changed(os.path.join(outdir, "ContextMenuDefault.inc"), gen_contextmenu(src))
    write_if_changed(os.path.join(outdir, "ScintillaKeyTable.inc"), gen_scintillakeys(src))


if __name__ == "__main__":
    main()
