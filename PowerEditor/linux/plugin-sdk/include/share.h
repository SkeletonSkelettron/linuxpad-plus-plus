// Notepad++ Linux plugin SDK: share modes of _fsopen/_wfsopen (files are not locked on Linux).
#pragma once
#include <windows.h>
#define _SH_DENYRW 0x10
#define _SH_DENYWR 0x20
#define _SH_DENYRD 0x30
#define _SH_DENYNO 0x40
#define _SH_SECURE 0x80
#define _fsopen(name, mode, share) fopen(name, mode)
#define _wfsopen(name, mode, share) _wfopen(name, mode)
